// Fetches the PokeSprite item icons the Adventure bag uses into assets/items/ and writes data/adv/item-sprites.js (id -> file).
// Source: github.com/msikma/pokesprite, items/<category>/<name>.png (32x32), pinned to a commit so the pixels never change under us.
// Item ids come from src/adv-party.js (ITEMS, STONES, tm_<move>): an id missing from MAP is reported as unmatched and falls back to the drawn icon in the game.
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PIN = 'c5aaa610ff2acdf7fd8e2dccd181bca8be9fcb3e';   // msikma/pokesprite master, 2022-07-22
const RAW = `https://raw.githubusercontent.com/${'msikma/pokesprite'}/${PIN}/items/`;
const OUT = path.join(ROOT, 'assets/items');

// game item id -> PokeSprite <category>/<name>
const MAP = {
  pokeball: 'ball/poke', greatball: 'ball/great', ultraball: 'ball/ultra', masterball: 'ball/master',
  potion: 'medicine/potion', superpotion: 'medicine/super-potion', hyperpotion: 'medicine/hyper-potion', maxpotion: 'medicine/max-potion', fullrestore: 'medicine/full-restore',
  antidote: 'medicine/antidote', paralyzeheal: 'medicine/paralyze-heal', awakening: 'medicine/awakening', burnheal: 'medicine/burn-heal', iceheal: 'medicine/ice-heal', fullheal: 'medicine/full-heal',
  revive: 'medicine/revive', maxrevive: 'medicine/max-revive', rarecandy: 'medicine/rare-candy',
  fishingrod: 'key-item/fishing-rod', bike: 'key-item/bicycle',
  firestone: 'evo-item/fire-stone', waterstone: 'evo-item/water-stone', thunderstone: 'evo-item/thunder-stone', leafstone: 'evo-item/leaf-stone', moonstone: 'evo-item/moon-stone', sunstone: 'evo-item/sun-stone',
  shinystone: 'evo-item/shiny-stone', duskstone: 'evo-item/dusk-stone', dawnstone: 'evo-item/dawn-stone', icestone: 'evo-item/ice-stone', ovalstone: 'evo-item/oval-stone',
};
// TM discs are coloured by the move's type: tm_<move> -> tm/<type>
const TYPES = ['bug', 'dark', 'dragon', 'electric', 'fairy', 'fighting', 'fire', 'flying', 'ghost', 'grass', 'ground', 'ice', 'normal', 'poison', 'psychic', 'rock', 'steel', 'water'];
const FALLBACK = 'etc/unknown-item';

// ids the game can hold (parsed from adv-party.js so a new item shows up here as unmatched until mapped)
const src = fs.readFileSync(path.join(ROOT, 'src/adv-party.js'), 'utf8');
const items = src.slice(src.indexOf('ITEMS: {'), src.indexOf('STONES:')), ids = [...items.matchAll(/^\s{4}([a-z]+): \{/gm)].map(m => m[1]);
const stones = [...src.match(/STONES: \[([^\]]*)\]/)[1].matchAll(/'([a-z]+)'/g)].map(m => m[1]);
const all = [...ids, ...stones], unmatched = all.filter(id => !MAP[id]);

const want = new Map();   // file name in assets/items -> category/name
for (const id of all) if (MAP[id]) want.set(id + '.png', MAP[id]);
for (const t of TYPES) want.set('tm-' + t + '.png', 'tm/' + t);
want.set('unknown.png', FALLBACK);
fs.mkdirSync(OUT, { recursive: true });
for (const [file, rel] of want) {
  const f = path.join(OUT, file);
  if (!fs.existsSync(f)) { const r = await fetch(RAW + rel + '.png'); if (!r.ok) throw new Error(rel + ' ' + r.status); fs.writeFileSync(f, Buffer.from(await r.arrayBuffer())); }
}
const files = {}; for (const id of all) if (MAP[id]) files[id] = 'assets/items/' + id + '.png';
fs.writeFileSync(path.join(ROOT, 'data/adv/item-sprites.js'),
  '// generated by tools/fetch-item-sprites.mjs: PokeSprite item icons (msikma/pokesprite @ ' + PIN.slice(0, 7) + '), 32x32, drawn at whole-number scale\n' +
  'window.ADV_ITEM_SPRITES = ' + JSON.stringify({ size: 32, files, tm: Object.fromEntries(TYPES.map(t => [t, 'assets/items/tm-' + t + '.png'])), unknown: 'assets/items/unknown.png' }, null, 1) + ';\n');
console.log(`${want.size} icons in assets/items, ${all.length} item ids, ${all.length - unmatched.length} matched`);
if (unmatched.length) console.log('unmatched (drawn icon is used):', unmatched.join(', '));
