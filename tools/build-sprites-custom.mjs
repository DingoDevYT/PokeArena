// Points mega forms that have no official PMDCollab body art at our custom sheets in assets/sprite-custom/<key>/.
// Writes data/sprites-custom.js (loaded after data/sprites.js). Usage: node tools/build-sprites-custom.mjs
import fs from 'node:fs';
import vm from 'node:vm';

const ctx = { window: {} };
vm.runInNewContext(fs.readFileSync('data/sprites.js', 'utf8'), ctx);
const SPRITES = ctx.window.SPRITES, out = {}, seeded = {};
// the preview target dummy (Substitute doll) is not a dex species: seed its entry
const DUMMY = JSON.parse(fs.readFileSync('assets/sprite/dummy/entry.json', 'utf8')); // official PMDCollab Substitute doll (tools/fetch-dummy.mjs)
SPRITES.dummy = DUMMY; // overrides the placeholder fetch-sprites borrows for it
// only finished sets (an agent writes _anims.json + _preview.png last)
for (const key of fs.readdirSync('assets/sprite-custom').filter(k => ['_anims.json', '_preview.png'].every(f => fs.existsSync(`assets/sprite-custom/${k}/${f}`)))) {
  // megas without any official art start as a copy of the base species; sheets they lack stay the base's
  const base = SPRITES[key] ? null : SPRITES[key.split('-')[0]] && key.split('-')[0];
  if (!SPRITES[key] && !base) { console.warn('skip (no base sprite): ' + key); continue; }
  if (base) seeded[key] = base;
  const meta = JSON.parse(fs.readFileSync(`assets/sprite-custom/${key}/_anims.json`, 'utf8'));
  out[key] = {};
  // partial megas (official sheets for some anims, ours for the rest): look sheets up in the base species too
  for (const [name, a] of Object.entries({ ...SPRITES[key.split('-')[0]]?.anims, ...SPRITES[base || key].anims })) {
    const sheet = a.file.split('/').pop().replace('-Anim.png', '');
    if (meta[sheet]) out[key][name] = { ...a, file: `assets/sprite-custom/${key}/${sheet}-Anim.png`, ...meta[sheet] };
  }
  console.assert(Object.keys(out[key]).length, 'no anims matched for ' + key);
}
fs.writeFileSync('data/sprites-custom.js', `// Generated by tools/build-sprites-custom.mjs\nconst CUSTOM_ANIMS = ${JSON.stringify(out)};\nwindow.SPRITES.dummy = ${JSON.stringify(DUMMY)};\nconst SEEDED = ${JSON.stringify(seeded)};\nfor (const k in SEEDED) window.SPRITES[k] ||= JSON.parse(JSON.stringify(window.SPRITES[SEEDED[k]]));\nfor (const k in CUSTOM_ANIMS) Object.assign(window.SPRITES[k].anims, CUSTOM_ANIMS[k]);\n`);
console.log(Object.entries(out).map(([k, v]) => `${k}: ${Object.keys(v).length} anims`).join(', '));
