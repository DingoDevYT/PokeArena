// Fetches every SpriteCollab emotion portrait for each key in data/sprites.js.
// Writes assets/portrait/<key>/<Emotion>.png and data/portraits.js.
// Same cache + polite fetching as fetch-sprites.mjs (6 at a time, backoff, 404s remembered).
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const RAW = 'https://raw.githubusercontent.com/PMDCollab/SpriteCollab/master/';
const CACHE = path.join(os.tmpdir(), 'pokearena-spritecollab');

let active = 0;
const waiting = [];
async function limited(fn) {
  if (active >= 6) await new Promise(r => waiting.push(r));
  active++;
  try { return await fn(); } finally { active--; waiting.shift()?.(); }
}
async function get(url) {
  return limited(async () => {
    for (let i = 1; ; i++) {
      try {
        const res = await fetch(url);
        if (res.status === 404) return null;
        if (!res.ok) throw new Error(`HTTP ${res.status}`);
        return Buffer.from(await res.arrayBuffer());
      } catch (e) {
        if (i >= 3) throw new Error(`${url}: ${e.message}`);
        await new Promise(r => setTimeout(r, 1000 * 2 ** i));
      }
    }
  });
}
async function download(url, file) {
  if (fs.existsSync(file) && fs.statSync(file).size > 0) return file;
  const miss = path.join(CACHE, '404', encodeURIComponent(url));
  if (fs.existsSync(miss)) return null;
  const buf = await get(url);
  if (!buf) { fs.mkdirSync(path.dirname(miss), { recursive: true }); fs.writeFileSync(miss, ''); return null; }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, buf);
  return file;
}

const window = {};
new Function('window', fs.readFileSync('data/sprites.js', 'utf8'))(window);
const tracker = JSON.parse(fs.readFileSync(await download(RAW + 'tracker.json', path.join(CACHE, 'tracker.json')), 'utf8'));

const out = {};
await Promise.all(Object.keys(window.SPRITES).map(async key => {
  const [d, f] = key.split('-');
  const form = f ? String(f).padStart(4, '0') : '';
  const group = form ? tracker[d]?.subgroups?.[form] : tracker[d];
  // Tracker values are lock flags; key presence means the file exists. '^' = flipped variant, unused.
  const emos = Object.keys(group?.portrait_files || {}).filter(e => !e.includes('^'));
  const got = {};
  await Promise.all(emos.map(async e => {
    const file = `assets/portrait/${key}/${e}.png`;
    if (await download(`${RAW}portrait/${form ? `${d}/${form}` : d}/${e}.png`, file)) got[e] = file;
  }));
  out[key] = got;
}));
// Forms with no portraits of their own reuse the base species' set (same as fetch-sprites does for Normal).
const borrow = {};
for (const key of Object.keys(out)) if (!out[key].Normal && key.includes('-') && out[key.split('-')[0]]) borrow[key] = key.split('-')[0];
for (const key in borrow) out[key] = out[borrow[key]];

const sorted = Object.fromEntries(Object.keys(out).sort().map(k => [k, Object.fromEntries(Object.keys(out[k]).sort().map(e => [e, out[k][e]]))]));
// On disk: emotion names per key (paths are assets/portrait/<key>/<Emotion>.png) or the key whose set it borrows.
const R = Object.fromEntries(Object.keys(sorted).map(k => [k, borrow[k] || Object.keys(sorted[k])]));
fs.writeFileSync('data/portraits.js', `// Generated by tools/fetch-portraits.mjs
window.PORTRAITS = (R => {
  const P = {};
  for (const k in R) if (Array.isArray(R[k])) P[k] = Object.fromEntries(R[k].map(e => [e, \`assets/portrait/\${k}/\${e}.png\`]));
  for (const k in R) if (!Array.isArray(R[k])) P[k] = P[R[k]];
  return P;
})(${JSON.stringify(R)});
`);
const check = {};
new Function('window', fs.readFileSync('data/portraits.js', 'utf8'))(check);
console.assert(JSON.stringify(check.PORTRAITS) === JSON.stringify(sorted), 'portraits.js does not expand back to the same data');
console.log(`data/portraits.js: ${Math.round(fs.statSync('data/portraits.js').size / 1024)} KB`);

const keys = Object.keys(sorted), count = {};
for (const k of keys) for (const e of Object.keys(sorted[k])) count[e] = (count[e] || 0) + 1;
console.log(`keys: ${keys.length}`);
console.log(Object.entries(count).sort((a, b) => b[1] - a[1]).map(([e, c]) => `${e} ${c}`).join(', '));
console.log(`only Normal: ${keys.filter(k => Object.keys(sorted[k]).length <= 1).join(' ')}`);
