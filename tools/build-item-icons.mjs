// Bakes held-item icons for every item in data/dex.js from PokeSprite (msikma/pokesprite inventory sprites).
// Run from project root: node tools/build-item-icons.mjs   (re-run after build-dex adds items)
// Writes assets/ui/items.png (32x32 cells, 16 per row) + data/item-icons.js (item id -> cell index).
// Downloads stay in tools/.cache/pokesprite/ and are only read as data (item-map.json as JSON, icons decoded as PNG).
import { Dex } from '@pkmn/dex';
import { PNG } from 'pngjs';
import fs from 'fs';
import path from 'path';

const CACHE = 'tools/.cache/pokesprite', RAW = 'https://raw.githubusercontent.com/msikma/pokesprite/master/';
const CELL = 32, COLS = 16, d = Dex.forGen(9);

async function get(url, file) {
  if (fs.existsSync(file)) return fs.statSync(file).size ? fs.readFileSync(file) : null;
  for (let i = 0; ; i++) {
    try {
      const r = await fetch(url, { headers: { 'User-Agent': 'pokearena-build' } });
      const buf = r.status === 404 ? Buffer.alloc(0) : r.ok ? Buffer.from(await r.arrayBuffer()) : null;
      if (!buf) throw new Error(`${r.status} ${url}`);
      fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, buf);
      return buf.length ? buf : null;
    } catch (e) { if (i >= 3) throw e; await new Promise(r => setTimeout(r, 1000 * 2 ** i)); }
  }
}

const map = JSON.parse(await get(RAW + 'data/item-map.json', `${CACHE}/item-map.json`));
const win = {};
new Function('window', fs.readFileSync('data/dex.js', 'utf8'))(win);
const ids = Object.keys(win.DEX.items).sort(), icons = [], missing = [];
for (const id of ids) {
  const p = map['item_' + String(d.items.get(id).num).padStart(4, '0')];
  const buf = p && await get(`${RAW}items/${p}.png`, `${CACHE}/items/${p}.png`);
  if (buf) icons.push([id, PNG.sync.read(buf)]); else missing.push(id);
}
const out = new PNG({ width: COLS * CELL, height: Math.max(1, Math.ceil(icons.length / COLS)) * CELL });
icons.forEach(([, im], i) => {
  const w = Math.min(CELL, im.width), h = Math.min(CELL, im.height);
  PNG.bitblt(im, out, 0, 0, w, h, (i % COLS) * CELL + ((CELL - w) >> 1), Math.floor(i / COLS) * CELL + ((CELL - h) >> 1));
});
fs.mkdirSync('assets/ui', { recursive: true });
fs.writeFileSync('assets/ui/items.png', PNG.sync.write(out));
fs.writeFileSync('data/item-icons.js', `// Generated by tools/build-item-icons.mjs from PokeSprite (msikma/pokesprite) item sprites.
// assets/ui/items.png holds ${CELL}x${CELL} cells, ${COLS} per row; ITEM_ICONS.cells maps item id -> cell index.
window.ITEM_ICONS = { file: 'assets/ui/items.png', size: ${CELL}, cols: ${COLS}, cells: ${JSON.stringify(Object.fromEntries(icons.map(([id], i) => [id, i])))} };
`);
console.log(`items.png: ${icons.length} icons`);
if (missing.length) console.log(`no icon: ${missing.join(' ')}`);
